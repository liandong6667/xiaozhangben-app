/* fix34：云闪付 / 银联这条路的真实文案
   ---------------------------------------------------------------
   2026-10-26 用户报：在「胖乖生活」用洗衣服务，用**云闪付**付了 2.5 元，
   没记上；同一晚银行到账的那笔记上了。

   查的顺序是先拿真实文案过一遍判定，而不是猜。
   云闪付的标准通知文案是「您已成功支付2.50元」—— 里面既没有「支付成功」，
   也没有「已支付」（是「已成功支付」，中间多了两个字），
   于是 strict 判定整条不认。这条就是本次要锁住的第一个坑。

   验证点：
     1. 云闪付各类通知 → 都要能记上，金额必须是 2.5（不是日期、不是尾号）
     2. 建行/银行的消费短信 → 都要能记上，金额要跳过尾号和余额
     3. 商户名「胖乖生活」要抓得出来（抓不到也得记账，只是标题差一点）
     4. 收入那条照样是收入，不能被这次改动带偏
     5. 聊天里的「给你 2.5 元」不能被记成账 */
(function(){
  var log = [];
  function ok(n, c){ log.push((c ? "Y" : "N") + n); }
  function near(n, got, want){ log.push((Math.abs(+got - want) < 0.005 ? "Y" : "N") + n + "(" + got + ")"); }

  function one(label, app, text){
    var p = null;
    try{ p = parseNotify({ app: app, src: "notify", title: "", text: text, ts: 1793000000000 }); }
    catch(e){ log.push("N" + label + "(抛异常 " + e.message + ")"); return null; }
    if(!p){ log.push("N" + label + "(没记上)"); return null; }
    return p;
  }

  setTimeout(function(){
    try{
      /* ===== 1. 云闪付：最常见的几种写法 ===== */
      var p1 = one("1a", "云闪付", "您已成功支付2.50元");
      if(p1) near("1a-金额", p1.amt, 2.5);

      var p2 = one("1b", "云闪付", "支付成功 金额2.50元 收款方：胖乖生活");
      if(p2){ near("1b-金额", p2.amt, 2.5); ok("1b-商户", /胖乖生活/.test(p2.peer || "")); }

      var p3 = one("1c", "云闪付", "您向胖乖生活付款2.50元，已从尾号6631卡扣款");
      if(p3){ near("1c-金额", p3.amt, 2.5); ok("1c-商户", /胖乖生活/.test(p3.peer || "")); }

      var p4 = one("1d", "云闪付", "交易提醒：您尾号6631的银行卡消费人民币2.50元");
      if(p4) near("1d-金额", p4.amt, 2.5);

      var p5 = one("1e", "云闪付", "支付成功，付款金额 ¥2.50");
      if(p5) near("1e-金额", p5.amt, 2.5);

      /* 云闪付的「交易已完成」写法：既没有"支付成功"也没有"已支付" */
      var p6 = one("1f", "云闪付", "您有一笔2.50元的交易已完成");
      if(p6) near("1f-金额", p6.amt, 2.5);

      /* 免密 / 自动扣款：上一轮 0.20 元那笔就是「自动扣款成功」，
         读屏那边原来不认这个词，这里一并锁住 */
      var p7 = one("1g", "云闪付", "小额免密支付成功，金额2.50元");
      if(p7) near("1g-金额", p7.amt, 2.5);

      var p8 = one("1h", "云闪付", "自动扣款成功2.50元");
      if(p8) near("1h-金额", p8.amt, 2.5);

      /* ===== 2. 银行的消费短信（短信通道走的是同一套解析） ===== */
      var p9 = one("2a", "短信", "您尾号6631的储蓄卡10月26日22:31在胖乖生活消费人民币2.50元，余额5,320.18元。");
      if(p9){
        near("2a-金额", p9.amt, 2.5);
        ok("2a-商户", /胖乖生活/.test(p9.peer || ""));
        ok("2a-是支出", p9.type === "expense");
      }

      var p10 = one("2b", "短信", "【建设银行】您账户6631于10月26日22:31向胖乖生活支付2.50元。");
      if(p10) near("2b-金额", p10.amt, 2.5);

      var p11 = one("2c", "短信", "您尾号6631账户10月26日22:31消费2.50元，可用余额5320.18元。");
      if(p11) near("2c-金额", p11.amt, 2.5);

      /* ===== 3. 收入那条：不能被这次改动带偏 ===== */
      var p12 = one("3a", "短信", "【建设银行】您账户6631于10月26日21:03收入人民币200.00元。");
      if(p12){ near("3a-金额", p12.amt, 200); ok("3a-是收入", p12.type === "income"); }

      /* 别人付给你：「向您支付」也是收入。这次给支出词补了「向 XX 支付」，
         必须确保没把方向带反 —— 反向验证会盯这一条。 */
      var p13 = one("3b", "短信", "【建设银行】您账户6631于10月26日20:10收到张三向您支付人民币200.00元。");
      if(p13){ near("3b-金额", p13.amt, 200); ok("3b-是收入", p13.type === "income"); }

      /* 聊天过滤不归网页侧管：原生 PayFilter 的 CHAT_NOISE 已经在入队前挡掉了
         （「张三: 转账 100.00元」「给你100元」两条用例见
          .build/tests/javacheck/PayFilterTest.java）。
         这里只确认一件事：万一真有一条聊天预览漏到网页侧，
         商户名也不能被当成"张三"——那是人名，不是店。 */
      var chat = parseNotify({ app: "微信", src: "notify", title: "张三",
                               text: "张三: 给你 2.5 元", ts: 1793000000000 });
      ok("4a 聊天预览不记账，也不能把人名当商户", chat === null);

      /* 加了聊天预览拦截之后，微信**真的**支付通知必须照旧能记 ——
         它们也是「名字: 一句话」的形状，只有"完成词"能区分开。
         这几条是护栏：谁要是把拦截写宽了，这里立刻红。 */
      var real1 = one("4b", "微信", "微信支付: 你已支付 ¥13.80");
      if(real1) near("4b-金额", real1.amt, 13.8);
      var real2 = one("4c", "微信", "微信支付: 付款金额 ¥23.50");
      if(real2) near("4c-金额", real2.amt, 23.5);
      ok("4d 聊天里说「我转你 100 元」不记账",
         parseNotify({ app: "微信", src: "notify", title: "张三",
                       text: "张三: 我转你 100 元", ts: 1793000000000 }) === null);

      /* ===== 5. 待付款 / 支付失败仍然不许记 ===== */
      ok("5a 待付款不记", parseNotify({ app: "微信", src: "notify", text: "待支付 ¥2.50", ts: 1793000000000 }) === null);
      ok("5b 支付失败不记", parseNotify({ app: "微信", src: "notify", text: "支付失败 ¥2.50", ts: 1793000000000 }) === null);

      document.title = "fix34 " + log.filter(function(s){ return s[0] === "Y"; }).length + "/" + log.length +
        " | " + log.join(" | ");
    }catch(e){
      document.title = "fix34 ERR: " + e.message + " | " + log.join(" | ");
    }
  }, 700);
})();
